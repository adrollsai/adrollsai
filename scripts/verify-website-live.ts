/**
 * Prove the WEBSITE builder, not just landing pages.
 *
 * `ensureTenantSite` builds a tenant's full site (home + offerings from the catalogue) and writes
 * it to landing_pages with slug 'index'. This runs it for the owner's real account, then fetches the
 * result through the actual public route and inspects the HTML and the rendered page.
 */
import fs from 'node:fs';
import dotenv from 'dotenv';
import { createClient } from '@supabase/supabase-js';
import { ensureTenantSite, buildSiteHtml } from '../lib/automation/site-builder';

dotenv.config({ path: '.env.local', quiet: true });
const admin = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY!,
  { auth: { persistSession: false } },
);
const OWNER = 'bc63c065-9bcc-4793-bedc-f0960406425b';

const results: { step: string; ok: boolean; detail?: string }[] = [];
const record = (step: string, ok: boolean, detail = '') => {
  results.push({ step, ok, detail });
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${step}${detail ? `  — ${detail}` : ''}`);
};

const { data: before } = await admin
  .from('landing_pages')
  .select('id, updated_at')
  .eq('user_id', OWNER)
  .eq('slug', 'index')
  .maybeSingle();

console.log('▸ building the tenant site (home + catalogue)…\n');
const started = Date.now();
const built = await ensureTenantSite(admin, OWNER);
console.log(`returned in ${((Date.now() - started) / 1000).toFixed(1)}s:`, JSON.stringify(built).slice(0, 300));

const { data: after } = await admin
  .from('landing_pages')
  .select('id, slug, title, html_content, updated_at')
  .eq('user_id', OWNER)
  .eq('slug', 'index')
  .maybeSingle();

record('an index site row exists', Boolean(after?.id), after ? `slug=${after.slug}` : 'missing');
record(
  'it was (re)generated by this run',
  Boolean(!before || (after && before.updated_at !== after.updated_at)),
  after?.updated_at ?? '',
);
const html = String(after?.html_content ?? '');
record('it has real HTML', html.length > 2000, `${html.length} chars`);
record('it names the business', /nobogent/i.test(html), 'business name present');
record(
  'it is a multi-section site, not a single card',
  (html.match(/<section/gi) || []).length >= 3,
  `${(html.match(/<section/gi) || []).length} sections`,
);
record(
  'it is responsive and self-contained',
  /name="viewport"/.test(html) && !/<link[^>]+href="https?:\/\//i.test(html),
  'viewport meta, no external CSS',
);
record(
  'it carries contact or CTA affordances',
  /(call|whatsapp|contact|book)/i.test(html),
  'CTA language present',
);

// Fetch through the real public route on the local server.
const url = `http://localhost:3000/shared/${OWNER}/index`;
const res = await fetch(url, { redirect: 'follow' }).catch(() => null);
const body = res ? await res.text() : '';
record('the public route serves it', !!res && res.status === 200, res ? `HTTP ${res.status}, ${body.length} bytes` : 'no response');
if (body) fs.writeFileSync('C:\\Users\\Adrolls\\Desktop\\nobo-e2e\\site-index.html', body);

const failed = results.filter((r) => !r.ok);
console.log(`\n${results.length - failed.length}/${results.length} checks passed`);
console.log(`site url: ${url}`);
process.exitCode = failed.length ? 1 : 0;
