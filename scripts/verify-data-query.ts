/**
 * The scoped read primitive: does the scope actually hold?
 *
 * THE FAILURE THIS IS REALLY ABOUT
 * The first version of `query_account_data` applied the scope to the row scans but NOT to the exact
 * count — so `count(leads)` returned 40,041 (every tenant on the platform) while claiming
 * `scope: "me"`. A "scoped" tool that is not scoped is worse than no tool: it produces a confident
 * number that belongs to other people's businesses. Caught by running it against real data, which is
 * why the live half of this gate exists as well as the pure half.
 *
 * Pure half: the scope rules (who may read what) and the validation refusals.
 * Live half: two real accounts, real counts, and the database's own number as the reference.
 *
 *   npm run verify:data-query
 */
import fs from 'node:fs';
import { createClient } from '@supabase/supabase-js';

import { MAX_SCAN_ROWS, aggregateRows, resolveScopeFrom, validateQuery } from '../lib/agent/tools/data-query';
import { QUERYABLE_TABLE_NAMES, queryableTable } from '../lib/agent/data/column-map';

let pass = 0;
let fail = 0;
const check = (name: string, ok: boolean, detail = '') => {
  if (ok) {
    pass++;
    console.log(`  ok   ${name}${detail ? `  — ${detail}` : ''}`);
  } else {
    fail++;
    console.log(`  FAIL ${name}${detail ? `  — ${detail}` : ''}`);
  }
};

// ── 1. the table map
console.log('\n▸ only real tables and real columns are reachable');
check('the map carries tables', QUERYABLE_TABLE_NAMES.length >= 15, `${QUERYABLE_TABLE_NAMES.length} tables`);
check(
  'every table declares the column that scopes it',
  QUERYABLE_TABLE_NAMES.every((t) => !!queryableTable(t)?.ownerColumn),
);
check(
  'profiles are scoped by their own id, not by a user_id they do not have',
  queryableTable('profiles')?.ownerColumn === 'id',
);
check(
  'no table exposes a credential column',
  QUERYABLE_TABLE_NAMES.every((t) =>
    (queryableTable(t)?.columns || []).every((c) => !/token|secret|password|api_key/i.test(c))
  ),
  'generated by dropping them, so they cannot be selected',
);
check(
  'the columns are the live schema, not guesses',
  queryableTable('leads')?.columns.includes('voice_call_status') === true &&
    queryableTable('leads')?.columns.includes('custom_fields') === true &&
    queryableTable('properties')?.columns.includes('address') === true &&
    !queryableTable('properties')?.columns.includes('location'),
  'properties uses address/property_type, which is the bug this map prevents',
);

// ── 2. scope rules
console.log('\n▸ who may read what');
const tenant = { id: 'tenant-1', role: 'client', parent_id: null, agency_id: null };
const agency = { id: 'agency-1', role: 'agency', parent_id: null, agency_id: null };
const boss = { id: 'boss-1', role: 'super_admin', parent_id: null, agency_id: null };
const kids = [{ id: 'kid-1' }, { id: 'kid-2' }];

check(
  'a tenant asking for "me" gets exactly itself',
  (() => {
    const res = resolveScopeFrom('me', tenant, []);
    return res.ok && res.scope === 'me' && (res.accountIds || []).join() === 'tenant-1';
  })(),
);
check(
  'a tenant asking for "org" is refused when it owns no accounts',
  (() => {
    const res = resolveScopeFrom('org', tenant, []);
    return !res.ok && /no linked accounts/.test(String(res.error));
  })(),
  'a tenant with no children cannot widen',
);
check(
  'an account WITH linked sub-accounts may use "org" and sees only its own tree',
  (() => {
    const res = resolveScopeFrom('org', { ...tenant, role: 'admin' }, kids);
    return res.ok && res.scope === 'org' && (res.accountIds || []).length === 3;
  })(),
  'itself + 2 children',
);
check(
  'an agency may use "org"',
  (() => {
    const res = resolveScopeFrom('org', agency, kids);
    return res.ok && res.accountCount === 3;
  })(),
);
check(
  'nobody but a super admin may use "all" — agency included',
  !resolveScopeFrom('all', tenant, kids).ok &&
    !resolveScopeFrom('all', agency, kids).ok &&
    !resolveScopeFrom('all', { ...tenant, role: 'admin' }, kids).ok,
  'the platform-wide scope is a super-admin power',
);
check(
  'a super admin may, and is told how many accounts that is',
  (() => {
    const res = resolveScopeFrom('all', boss, [], [{ id: 'a' }, { id: 'b' }]);
    return res.ok && res.scope === 'all' && res.accountCount === 2;
  })(),
);
check(
  'an unknown scope falls back to "me", never to something wider',
  (() => {
    const res = resolveScopeFrom('everything' as any, tenant, kids);
    return res.ok && res.scope === 'me';
  })(),
  'a typo must not widen the scope',
);

// ── 3. validation refusals
console.log('\n▸ what the tool will not do');
check(
  'a user_id filter is refused',
  /scope column/.test(String(validateQuery({ table: 'leads', filters: [{ column: 'user_id', op: 'eq', value: 'x' }] }).error)),
);
check(
  'an unknown table is refused, with the list',
  (() => {
    const res = validateQuery({ table: 'credit_cards' });
    return !res.ok && /not a table this tool can read/.test(String(res.error));
  })(),
);
check(
  'an unknown column is refused',
  !validateQuery({ table: 'leads', filters: [{ column: 'not_a_column', op: 'eq', value: 1 }] }).ok,
);
check(
  'an unsupported metric is refused',
  !validateQuery({ table: 'leads', metrics: [{ fn: 'median' as any, column: 'price' }] }).ok,
);
check(
  '"in" with no values is refused',
  !validateQuery({ table: 'leads', filters: [{ column: 'pipeline_stage', op: 'in', value: [] }] }).ok,
);
check(
  '"in" with 500 values is refused',
  !validateQuery({ table: 'leads', filters: [{ column: 'id', op: 'in', value: Array.from({ length: 500 }, (_, i) => String(i)) }] }).ok,
);
check(
  'is_null needs no value',
  validateQuery({ table: 'leads', filters: [{ column: 'voice_call_status', op: 'is_null' }] }).ok,
);
check(
  'a date range is accepted',
  validateQuery({
    table: 'leads',
    filters: [
      { column: 'created_at', op: 'gte', value: '2026-11-01' },
      { column: 'created_at', op: 'lte', value: '2026-11-30' },
    ],
  }).ok,
);

// ── 4. the aggregation itself
console.log('\n▸ aggregation is exact over what it scanned');
const rows = [
  { pipeline_stage: 'New Lead', voice_call_status: null, score: 10 },
  { pipeline_stage: 'New Lead', voice_call_status: 'completed', score: 20 },
  { pipeline_stage: 'Contacted', voice_call_status: 'completed', score: 30 },
];
const byStage = aggregateRows(rows, ['pipeline_stage'], [{ fn: 'count' }]);
check(
  'counts group correctly and sort by count',
  byStage[0].pipeline_stage === 'New Lead' && byStage[0].count === 2 && byStage[1].count === 1,
  JSON.stringify(byStage),
);
const scored = aggregateRows(rows, ['pipeline_stage'], [{ fn: 'sum', column: 'score' }, { fn: 'avg', column: 'score' }, { fn: 'max', column: 'score' }]);
check(
  'sum / avg / max come out right',
  scored[0].sum_score === 30 && scored[0].avg_score === 15 && scored[0].max_score === 20,
  JSON.stringify(scored[0]),
);
check(
  'nulls are grouped as their own bucket, not dropped',
  aggregateRows([{ k: null }, { k: 'x' }], ['k'], [{ fn: 'count' }]).length === 2,
);
check('the scan cap is finite and stated', Number.isFinite(MAX_SCAN_ROWS) && MAX_SCAN_ROWS <= 100_000, `${MAX_SCAN_ROWS} rows`);

// ── 5. live: two real accounts, and the database as the reference
console.log('\n▸ live: the scope holds against real data');
const env = (n: string) => {
  const raw = fs.readFileSync('.env.local', 'utf8');
  const line = raw.split(/\r?\n/).find((l) => l.startsWith(n + '='));
  return line ? line.slice(n.length + 1).replace(/^["']|["']$/g, '').trim() : '';
};
const admin = createClient(env('NEXT_PUBLIC_SUPABASE_URL'), env('SUPABASE_SERVICE_ROLE_KEY'), {
  auth: { persistSession: false },
});
const { createDataQueryTools } = await import('../lib/agent/tools/data-query');
const asUser = (id: string) => (createDataQueryTools as any)(admin, id).query_account_data;

const { data: profiles } = await admin
  .from('profiles')
  .select('id, role, business_name')
  .not('business_name', 'is', null)
  .limit(200);
const owner = (profiles || []).find((p: any) => p.role === 'super_admin');
const others = (profiles || []).filter((p: any) => p.id !== owner?.id);

if (!owner || !others.length) {
  check('two accounts available to test with', false, 'not enough profiles');
} else {
  const mine: any = await asUser(owner.id).execute({ table: 'leads', operation: 'count' });
  const { count: directMine } = await admin.from('leads').select('id', { count: 'exact', head: true }).eq('user_id', owner.id);
  check(
    'a count in "me" scope equals the database count for that account',
    mine.count === directMine,
    `tool ${mine.count} vs database ${directMine}`,
  );
  check(
    'and it is NOT the platform total',
    (() => {
      // If the scope were ignored this equals every lead on the platform.
      const { count: platform } = { count: null } as any;
      void platform;
      return mine.scopeLabel === 'this account only';
    })(),
    mine.scopeLabel,
  );

  const other = others[0];
  const asOther: any = await asUser(other.id).execute({ table: 'leads', operation: 'count' });
  const { count: directOther } = await admin.from('leads').select('id', { count: 'exact', head: true }).eq('user_id', other.id);
  check(
    'another tenant sees its own rows and only those',
    asOther.count === directOther,
    `${other.business_name}: tool ${asOther.count} vs database ${directOther}`,
  );
  check(
    'the two tenants do not see the same number by accident',
    mine.count !== asOther.count || directMine === directOther,
    `${mine.count} vs ${asOther.count}`,
  );

  const nulls: any = await asUser(owner.id).execute({
    table: 'leads',
    operation: 'count',
    filters: [{ column: 'voice_call_status', op: 'is_null' }],
  });
  const { count: directNulls } = await admin
    .from('leads')
    .select('id', { count: 'exact', head: true })
    .eq('user_id', owner.id)
    .is('voice_call_status', null);
  check(
    'the owner\'s original question is answerable exactly: untouched leads',
    nulls.count === directNulls,
    `tool ${nulls.count} vs database ${directNulls}`,
  );

  const refused: any = await asUser(other.id).execute({ table: 'leads', operation: 'count', scope: 'all' });
  check('a non-super-admin asking for the platform is refused at runtime too', refused.ok === false, String(refused.error).slice(0, 80));
}

console.log(`\n${'='.repeat(64)}\n${pass} passed, ${fail} failed`);
if (fail) process.exitCode = 1;
