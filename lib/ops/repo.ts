/**
 * Finding the right file for a question, deterministically.
 *
 * This is the retrieval half of the owner's "ask anything about the app" console. It answers
 * "which files are relevant to this question?" — the model is then shown those files' own
 * header comments and told to answer from them, so the response is grounded in the code rather
 * than in what a model remembers about Next.js projects in general.
 *
 * WHY NOT EMBEDDINGS OR A VECTOR STORE
 * The same reason `lib/agent/skill-router.ts` gives, and it holds here: scoring is instant, has
 * no index to drift out of sync, needs no extra dependency, and produces a ranked list a human
 * can audit when an answer looks wrong. A codebase of ~1,900 files with this repo's habit of
 * writing a real prose header above every module does not need semantics to be searchable —
 * the words in the question are usually the words in the header.
 *
 * WHAT MAKES A HIT GOOD
 * Weighted, in order: the file PATH (asking about "the review gate" must find
 * lib/agent/review-gate.ts first), then exported symbol names, then the tables a file touches,
 * then the header prose. Path and symbols are exact and cheap; prose is fuzzy and ranked last
 * so a file that merely mentions a keyword cannot outrank the file that is named after it.
 *
 * The snapshot it reads is generated by `scripts/build-ops-repo-index.mjs` and committed,
 * because Vercel has no checkout. `scripts/verify-ops-watchdog.mjs` fails when its commit does
 * not match HEAD, so stale code cannot quietly answer questions as if it were current.
 */

import snapshotJson from './repo-snapshot.json';

/** One indexed file. Single-letter keys keep the committed snapshot small. */
interface SnapshotEntry {
  /** path */
  p: string;
  /** line count */
  l: number;
  /** header comment */
  h: string;
  /** exported symbol names */
  e?: string[];
  /** supabase tables / rpcs touched */
  t?: string[];
  /** HTTP verbs, for route handlers */
  r?: string[];
  /** body keyword signature — the most distinctive identifiers the file actually uses */
  b?: string;
}

export interface RepoSnapshotData {
  generatedAt: string;
  commit: string;
  branch: string;
  fileCount: number;
  files: SnapshotEntry[];
}

/**
 * The snapshot, typed by hand.
 *
 * The explicit cast is deliberate: without it TypeScript infers a literal type for all ~1,900
 * entries, which is both useless (nothing writes to it) and slow to check. The shape is
 * asserted by `repoSnapshotMeta()` and by the verify gate instead.
 */
const SNAPSHOT = snapshotJson as unknown as RepoSnapshotData;

/** Where the snapshot came from — surfaced so the owner knows how current the answer is. */
export function repoSnapshotMeta(): {
  commit: string;
  branch: string;
  generatedAt: string;
  fileCount: number;
} {
  return {
    commit: SNAPSHOT.commit,
    branch: SNAPSHOT.branch,
    generatedAt: SNAPSHOT.generatedAt,
    fileCount: SNAPSHOT.fileCount,
  };
}

export interface RepoHit {
  path: string;
  lines: number;
  score: number;
  /** Which query words actually matched, for an answer that cites its evidence. */
  matched: string[];
  header: string;
  exports: string[];
  tables: string[];
  routes: string[];
}

/**
 * Words that carry no signal in this codebase.
 *
 * Kept deliberately short. An over-eager stopword list removes the word that mattered ("how do
 * we send" — 'send' is not a stopword), and ranking already discounts words that hit every file.
 */
const STOPWORDS = new Set([
  'the', 'and', 'for', 'how', 'does', 'did', 'was', 'were', 'are', 'what', 'when', 'where',
  'which', 'who', 'why', 'with', 'from', 'that', 'this', 'there', 'here', 'have', 'has', 'had',
  'can', 'could', 'would', 'should', 'our', 'you', 'your', 'its', 'it', 'is', 'be', 'to', 'of',
  'in', 'on', 'at', 'as', 'by', 'or', 'if', 'we', 'us', 'do', 'me', 'my', 'not', 'but', 'all',
  'any', 'get', 'got', 'about', 'into', 'out', 'up', 'down', 'app', 'code', 'work', 'works',
]);

/** Split a question into candidate search terms. */
export function tokenize(query: string): string[] {
  return [...new Set(
    (query || '')
      .toLowerCase()
      // Keep inner dots and dashes so "review-gate" and "app/api" survive as one token each.
      .split(/[^a-z0-9._\-/]+/)
      .map((token) => token.replace(/^[._\-/]+|[._\-/]+$/g, ''))
      .filter((token) => token.length >= 3 && !STOPWORDS.has(token)),
  )];
}

/**
 * Cheap suffix folding, so "messages"/"message", "sending"/"send" and "rendered"/"render"
 * are the same word for ranking.
 *
 * Not a stemmer. A real one would be a dependency and a source of surprises; dropping four
 * common English suffixes catches the plural/gerund mismatch that actually breaks searches over
 * identifier names, and nothing else here needs linguistics.
 */
export function variants(token: string): string[] {
  const forms = new Set([token]);
  for (const suffix of ['ing', 'ed', 'es', 's']) {
    if (token.endsWith(suffix) && token.length - suffix.length >= 3) {
      forms.add(token.slice(0, -suffix.length));
    }
  }
  return [...forms];
}

/**
 * Score every file against the query and return the best `limit`.
 *
 * `minScore` exists so an unrelated question returns nothing rather than the least-bad file in
 * the repo. An answer built on an irrelevant file is worse than "I could not find that",
 * because it looks like knowledge.
 */
export function searchRepo(
  query: string,
  options: { limit?: number; minScore?: number } = {},
): RepoHit[] {
  const limit = Math.max(1, Math.min(30, options.limit ?? 8));
  const minScore = options.minScore ?? 6;
  const tokens = tokenize(query);
  if (!tokens.length) return [];

  const hits: RepoHit[] = [];

  for (const entry of SNAPSHOT.files) {
    const path = entry.p.toLowerCase();
    const header = (entry.h || '').toLowerCase();
    const body = (entry.b || '').toLowerCase();
    const exportsLower = (entry.e || []).map((name) => name.toLowerCase());
    const tablesLower = (entry.t || []).map((name) => name.toLowerCase());

    let score = 0;
    const matched: string[] = [];

    for (const token of tokens) {
      const forms = variants(token);
      const any = (haystack: string) => forms.some((form) => haystack.includes(form));
      let tokenScore = 0;

      // The path is the strongest signal in a well-named repo: asking about "review gate"
      // should rank lib/agent/review-gate.ts above everything that merely mentions it.
      if (any(path)) tokenScore += forms.some((form) => path.includes(`/${form}`)) ? 10 : 6;

      // An exported symbol matching the question is nearly as strong.
      if (exportsLower.some((name) => forms.includes(name))) tokenScore += 9;
      else if (exportsLower.some((name) => any(name))) tokenScore += 4;

      // "what writes to leads" is a table question, and tables are exactly indexable.
      if (tablesLower.some((table) => forms.includes(table))) tokenScore += 8;
      else if (tablesLower.some((table) => any(table))) tokenScore += 4;

      // Prose last, and capped per token, so a file that mentions a word 40 times cannot
      // bury a file that is named after it.
      if (any(header)) tokenScore += 3;
      if (header.includes(` ${token} `) || forms.some((form) => header.includes(` ${form} `))) tokenScore += 1;

      // The body signature is what rescues the three-quarters of this repo without a header
      // comment — it is how a question phrased differently from the file's own prose still
      // lands on the file that does the work.
      if (body && any(body)) tokenScore += 2;

      if (tokenScore > 0) {
        score += tokenScore;
        matched.push(token);
      }
    }

    // Reject an incidental single word, but never reject a file that a single word names.
    // Asking "where are whatsapp messages sent?" must surface lib/agent/tools/whatsapp.ts even
    // if that file's header happens to use different vocabulary — being named after the subject
    // is the strongest evidence there is, and an earlier two-token rule threw those away.
    if (score < minScore) continue;
    if (matched.length < 2 && score < 10) continue;

    hits.push({
      path: entry.p,
      lines: entry.l,
      score,
      matched,
      header: entry.h || '',
      exports: entry.e || [],
      tables: entry.t || [],
      routes: entry.r || [],
    });
  }

  return hits
    .sort((a, b) => b.score - a.score || a.path.localeCompare(b.path))
    .slice(0, limit);
}

/**
 * The retrieval results as text for a model prompt.
 *
 * Capped per file: eight files at 900 characters is about 2,000 tokens of context, which is
 * enough for the header of a well-documented module and orders of magnitude cheaper than
 * pasting the source. The model is told to cite paths, so a wrong answer is traceable.
 */
export function renderContextForPrompt(hits: readonly RepoHit[], options: { perFile?: number } = {}): string {
  if (!hits.length) return '(no file in the snapshot matched this question)';
  const perFile = Math.max(200, Math.min(2000, options.perFile ?? 900));

  return hits
    .map((hit) => {
      const facts: string[] = [`### ${hit.path} (${hit.lines} lines)`];
      if (hit.exports.length) facts.push(`exports: ${hit.exports.join(', ')}`);
      if (hit.tables.length) facts.push(`touches: ${hit.tables.join(', ')}`);
      if (hit.routes.length) facts.push(`http: ${hit.routes.join(', ')}`);
      if (hit.header) {
        const header = hit.header.length > perFile ? `${hit.header.slice(0, perFile)}…` : hit.header;
        facts.push('', header);
      }
      return facts.join('\n');
    })
    .join('\n\n---\n\n');
}

/**
 * Files that look like they belong together, so an answer can mention what else to read.
 *
 * Deliberately shallow (same directory, or same top-level module) — this is a "you may also
 * want" hint, not a call graph.
 */
export function relatedFiles(path: string, limit = 5): string[] {
  const directory = path.includes('/') ? path.slice(0, path.lastIndexOf('/')) : '';
  return SNAPSHOT.files
    .filter((entry) => entry.p !== path)
    .filter((entry) => (directory ? entry.p.startsWith(`${directory}/`) : !entry.p.includes('/')))
    .sort((a, b) => b.l - a.l)
    .slice(0, Math.max(0, limit))
    .map((entry) => entry.p);
}
