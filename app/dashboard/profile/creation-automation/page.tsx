'use client'

import { useState, useEffect } from 'react'
import { useRouter } from 'next/navigation'
import Link from 'next/link'
import {
  ArrowLeft,
  Sparkles,
  Film,
  Image as ImageIcon,
  Clock,
  Calendar,
  ChevronUp,
  ChevronDown,
  Plus,
  SlidersHorizontal,
  Check,
  RefreshCw,
  AlertCircle,
  HelpCircle,
  Play,
  Layers,
  Trash2,
  X,
  ExternalLink,
  MessageCircle,
  ShieldCheck,
  CheckCircle2,
  Sliders
} from 'lucide-react'
import { toast } from 'sonner'

interface QueueProduct {
  id: string
  title: string
  description: string
  price: string
  imageUrl: string
  autoGenerateDaily: boolean
  autoGenerateVideo: boolean
  orderIndex: number
  videoSettings: {
    duration: number
    customPrompt: string
    captionStyle: string
  }
  imageSettings: {
    dimensions: string
    timeOfDay: string
    customPrompt: string
  }
  stats: {
    lastImageDate: string | null
    lastVideoDate: string | null
    imageCount: number
    videoCount: number
  }
}

interface CadenceInfo {
  dailyActiveCount: number
  videoActiveCount: number
  totalProductsCount: number
  nextDailyProduct: { id: string; title: string; orderIndex: number } | null
  nextVideoProduct: { id: string; title: string; orderIndex: number } | null
  isVideoDueToday: boolean
  daysUntilNextVideo: number
  daysSinceLastVideo: number | null
  captionSpecification: {
    style: string
    animation: string
    position: string
    fontFamily: string
    fontSize: string
  }
}

interface ScheduleDay {
  dayIndex: number
  dayLabel: string
  dateFormatted: string
  imageProduct: { id: string; title: string; imageUrl: string } | null
  videoProduct: { id: string; title: string; imageUrl: string; duration: number } | null
  isVideoDay: boolean
}

export default function CreationAutomationPage() {
  const router = useRouter()
  const [loading, setLoading] = useState(true)
  const [savingOrder, setSavingOrder] = useState(false)
  const [queue, setQueue] = useState<QueueProduct[]>([])
  const [cadence, setCadence] = useState<CadenceInfo | null>(null)
  const [scheduleForecast, setScheduleForecast] = useState<ScheduleDay[]>([])
  const [impersonateId, setImpersonateId] = useState<string | null>(null)

  // Settings Modal State
  const [editingProduct, setEditingProduct] = useState<QueueProduct | null>(null)
  const [modalDuration, setModalDuration] = useState(30)
  const [modalCustomPrompt, setModalCustomPrompt] = useState('')
  const [isSavingSettings, setIsSavingSettings] = useState(false)

  // Add Product Modal State
  const [showAddModal, setShowAddModal] = useState(false)
  const [newTitle, setNewTitle] = useState('')
  const [newDescription, setNewDescription] = useState('')
  const [newPrice, setNewPrice] = useState('')
  const [newImageUrl, setNewImageUrl] = useState('')
  const [newDuration, setNewDuration] = useState(30)
  const [isCreatingProduct, setIsCreatingProduct] = useState(false)

  useEffect(() => {
    const urlParams = new URLSearchParams(window.location.search)
    const imp = urlParams.get('impersonate')
    setImpersonateId(imp)
    fetchAutomationData(imp)
  }, [])

  const fetchAutomationData = async (impId?: string | null) => {
    setLoading(true)
    try {
      const imp = impId !== undefined ? impId : impersonateId
      const res = await fetch(`/api/profile/creation-automation${imp ? `?impersonate=${imp}` : ''}`)
      if (!res.ok) throw new Error('Failed to load creation automation settings')
      const data = await res.json()
      if (data.success) {
        setQueue(data.queue || [])
        setCadence(data.cadence || null)
        setScheduleForecast(data.scheduleForecast || [])
      }
    } catch (err: any) {
      toast.error('Error loading automation data: ' + err.message)
    } finally {
      setLoading(false)
    }
  }

  // Handle reordering products
  const handleMoveProduct = async (fromIndex: number, toIndex: number) => {
    if (toIndex < 0 || toIndex >= queue.length) return
    const reordered = [...queue]
    const [movedItem] = reordered.splice(fromIndex, 1)
    reordered.splice(toIndex, 0, movedItem)

    // Update orderIndex locally for smooth feedback
    const normalized = reordered.map((item, idx) => ({
      ...item,
      orderIndex: idx + 1
    }))
    setQueue(normalized)

    // Sync with backend
    setSavingOrder(true)
    try {
      const orderedProductIds = normalized.map(p => p.id)
      const res = await fetch(`/api/profile/creation-automation${impersonateId ? `?impersonate=${impersonateId}` : ''}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          action: 'reorder',
          orderedProductIds
        })
      })
      if (!res.ok) throw new Error('Failed to persist order')
      toast.success('Round-Robin sequence updated!', {
        description: `Product #${toIndex + 1} will now be prioritized in rotation.`
      })
      // Refresh schedule forecast
      fetchAutomationData(impersonateId)
    } catch (err: any) {
      toast.error('Failed to save order: ' + err.message)
      fetchAutomationData(impersonateId)
    } finally {
      setSavingOrder(false)
    }
  }

  // Toggle Daily Creative
  const handleToggleDaily = async (product: QueueProduct) => {
    const nextVal = !product.autoGenerateDaily
    const updated = queue.map(p => p.id === product.id ? { ...p, autoGenerateDaily: nextVal } : p)
    setQueue(updated)

    try {
      const res = await fetch(`/api/profile/creation-automation${impersonateId ? `?impersonate=${impersonateId}` : ''}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          action: 'update_product_settings',
          propertyId: product.id,
          autoGenerateDaily: nextVal
        })
      })
      if (!res.ok) throw new Error('Failed to update daily setting')
      toast.success(nextVal ? `Added "${product.title}" to Daily Images` : `Paused Daily Images for "${product.title}"`)
      fetchAutomationData(impersonateId)
    } catch (err: any) {
      toast.error('Failed to update: ' + err.message)
      fetchAutomationData(impersonateId)
    }
  }

  // Toggle Video
  const handleToggleVideo = async (product: QueueProduct) => {
    const nextVal = !product.autoGenerateVideo
    const updated = queue.map(p => p.id === product.id ? { ...p, autoGenerateVideo: nextVal } : p)
    setQueue(updated)

    try {
      const res = await fetch(`/api/profile/creation-automation${impersonateId ? `?impersonate=${impersonateId}` : ''}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          action: 'update_product_settings',
          propertyId: product.id,
          autoGenerateVideo: nextVal
        })
      })
      if (!res.ok) throw new Error('Failed to update video setting')
      toast.success(nextVal ? `Enrolled "${product.title}" in 3-day video rotation` : `Paused videos for "${product.title}"`)
      fetchAutomationData(impersonateId)
    } catch (err: any) {
      toast.error('Failed to update: ' + err.message)
      fetchAutomationData(impersonateId)
    }
  }

  // Open settings modal for a product
  const handleOpenSettings = (product: QueueProduct) => {
    setEditingProduct(product)
    setModalDuration(product.videoSettings.duration || 30)
    setModalCustomPrompt(product.videoSettings.customPrompt || product.imageSettings.customPrompt || '')
  }

  // Save product settings
  const handleSaveSettings = async () => {
    if (!editingProduct) return
    setIsSavingSettings(true)
    try {
      const res = await fetch(`/api/profile/creation-automation${impersonateId ? `?impersonate=${impersonateId}` : ''}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          action: 'update_product_settings',
          propertyId: editingProduct.id,
          videoDuration: modalDuration,
          customPrompt: modalCustomPrompt
        })
      })
      if (!res.ok) throw new Error('Failed to save settings')
      toast.success(`Updated settings for "${editingProduct.title}"`)
      setEditingProduct(null)
      fetchAutomationData(impersonateId)
    } catch (err: any) {
      toast.error('Failed to save settings: ' + err.message)
    } finally {
      setIsSavingSettings(false)
    }
  }

  // Create & Add New Product
  const handleCreateProduct = async () => {
    if (!newTitle.trim() || !newDescription.trim()) {
      toast.error('Please enter product title and description')
      return
    }
    setIsCreatingProduct(true)
    try {
      const res = await fetch(`/api/profile/creation-automation${impersonateId ? `?impersonate=${impersonateId}` : ''}`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          action: 'add_product',
          title: newTitle.trim(),
          description: newDescription.trim(),
          price: newPrice.trim(),
          imageUrl: newImageUrl.trim(),
          autoGenerateDaily: true,
          autoGenerateVideo: true,
          videoDuration: newDuration
        })
      })
      if (!res.ok) throw new Error('Failed to add product')
      toast.success(`"${newTitle}" added to Creation Automation queue!`)
      setShowAddModal(false)
      setNewTitle('')
      setNewDescription('')
      setNewPrice('')
      setNewImageUrl('')
      fetchAutomationData(impersonateId)
    } catch (err: any) {
      toast.error('Failed to create product: ' + err.message)
    } finally {
      setIsCreatingProduct(false)
    }
  }

  return (
    <div className="min-h-screen bg-slate-50/50 pb-40 sm:pb-48">
      {/* Top Header */}
      <div className="sticky top-0 z-30 bg-white/80 backdrop-blur-md border-b border-slate-200/80 px-4 sm:px-8 py-4">
        <div className="max-w-6xl mx-auto flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div className="flex items-center gap-3">
            <button
              onClick={() => router.push(`/dashboard/profile${impersonateId ? `?impersonate=${impersonateId}` : ''}`)}
              className="p-2 -ml-2 rounded-xl text-slate-500 hover:text-slate-900 hover:bg-slate-100 transition-colors cursor-pointer"
              title="Back to Profile"
            >
              <ArrowLeft size={20} />
            </button>
            <div>
              <div className="flex items-center gap-2.5">
                <h1 className="text-xl sm:text-2xl font-black text-slate-900 tracking-tight">
                  Creation Automation
                </h1>
                <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-bold bg-amber-100 text-amber-800 border border-amber-200">
                  <Sparkles size={11} className="text-amber-600 fill-amber-500/20" />
                  Round-Robin Queue
                </span>
              </div>
              <p className="text-xs sm:text-sm text-slate-500 font-medium">
                Sequence your products for automatic daily marketing posters and 3-day video reel round-robin.
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2 self-start sm:self-auto">
            <button
              onClick={() => fetchAutomationData(impersonateId)}
              disabled={loading}
              className="p-2.5 rounded-xl border border-slate-200 text-slate-600 hover:text-slate-900 hover:bg-slate-50 transition-all cursor-pointer"
              title="Refresh Queue"
            >
              <RefreshCw size={16} className={loading ? 'animate-spin' : ''} />
            </button>

            <button
              onClick={() => setShowAddModal(true)}
              className="bg-indigo-600 hover:bg-indigo-700 text-white font-bold text-xs sm:text-sm py-2.5 px-4 rounded-xl shadow-sm hover:shadow transition-all flex items-center gap-2 cursor-pointer active:scale-95"
            >
              <Plus size={16} />
              <span>Add Product</span>
            </button>
          </div>
        </div>
      </div>

      <div className="max-w-6xl mx-auto px-4 sm:px-8 mt-6 space-y-6">
        {/* Rhythm & Status Cards */}
        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          {/* Card 1: Daily Creatives */}
          <div className="bg-white rounded-2xl p-5 border border-slate-200/80 shadow-sm relative overflow-hidden">
            <div className="absolute top-0 right-0 w-24 h-24 bg-violet-500/5 rounded-bl-full pointer-events-none" />
            <div className="flex items-center gap-3 mb-3">
              <div className="w-10 h-10 rounded-xl bg-violet-100 text-violet-700 flex items-center justify-center font-bold">
                <ImageIcon size={20} />
              </div>
              <div>
                <span className="text-[10px] font-bold text-slate-400 uppercase tracking-wider block">Cadence 1</span>
                <h3 className="text-sm font-extrabold text-slate-900">Daily Creatives (Image)</h3>
              </div>
            </div>
            <p className="text-xs text-slate-600 leading-relaxed font-medium mb-3">
              Generates a 3:4 branded poster every morning, cycling through products in order.
            </p>
            <div className="pt-3 border-t border-slate-100 flex items-center justify-between text-xs">
              <span className="text-slate-500 font-semibold">Active in Rotation:</span>
              <span className="font-bold text-violet-700 bg-violet-50 px-2 py-0.5 rounded-full border border-violet-100">
                {cadence?.dailyActiveCount || 0} Products
              </span>
            </div>
            {cadence?.nextDailyProduct && (
              <div className="mt-2 text-xs flex items-center justify-between">
                <span className="text-slate-500 font-semibold">⭐ Next Turn:</span>
                <span className="font-bold text-slate-800 truncate max-w-[140px]" title={cadence.nextDailyProduct.title}>
                  #{cadence.nextDailyProduct.orderIndex} {cadence.nextDailyProduct.title}
                </span>
              </div>
            )}
          </div>

          {/* Card 2: 3-Day Video Cadence */}
          <div className="bg-gradient-to-br from-amber-500/10 via-orange-500/5 to-white rounded-2xl p-5 border border-amber-200/80 shadow-sm relative overflow-hidden">
            <div className="flex items-center gap-3 mb-3">
              <div className="w-10 h-10 rounded-xl bg-amber-500 text-white flex items-center justify-center font-bold shadow-sm shadow-amber-500/20">
                <Film size={20} />
              </div>
              <div>
                <div className="flex items-center gap-1.5">
                  <span className="text-[10px] font-bold text-amber-700 uppercase tracking-wider block">Cadence 2</span>
                  <span className="bg-amber-100 text-amber-800 text-[9px] font-black px-1.5 py-0.2 rounded-full uppercase">Every 3rd Day</span>
                </div>
                <h3 className="text-sm font-extrabold text-slate-900">Luxury Video Reels</h3>
              </div>
            </div>
            <p className="text-xs text-slate-700 leading-relaxed font-medium mb-3">
              Produced <strong>every third day starting from Product #1</strong> with Seedance 2 photorealistic visuals.
            </p>
            <div className="pt-3 border-t border-amber-200/60 flex items-center justify-between text-xs">
              <span className="text-slate-600 font-semibold">Cadence Status:</span>
              {cadence?.isVideoDueToday ? (
                <span className="font-black text-emerald-700 bg-emerald-100 px-2 py-0.5 rounded-full border border-emerald-200">
                  🎬 Video Due Today!
                </span>
              ) : (
                <span className="font-bold text-amber-800 bg-amber-100 px-2 py-0.5 rounded-full border border-amber-200">
                  Due in {cadence?.daysUntilNextVideo || 1} day(s)
                </span>
              )}
            </div>
            {cadence?.nextVideoProduct && (
              <div className="mt-2 text-xs flex items-center justify-between">
                <span className="text-slate-600 font-semibold">🎬 Next Video Turn:</span>
                <span className="font-bold text-amber-950 truncate max-w-[140px]" title={cadence.nextVideoProduct.title}>
                  #{cadence.nextVideoProduct.orderIndex} {cadence.nextVideoProduct.title}
                </span>
              </div>
            )}
          </div>

          {/* Card 3: Golden Luxury Captions Engine */}
          <div className="bg-slate-900 text-white rounded-2xl p-5 border border-slate-800 shadow-sm relative overflow-hidden">
            <div className="flex items-center gap-3 mb-3">
              <div className="w-10 h-10 rounded-xl bg-amber-400 text-slate-950 flex items-center justify-center font-bold">
                <Sparkles size={20} />
              </div>
              <div>
                <span className="text-[10px] font-bold text-amber-400 uppercase tracking-wider block">Default Theme</span>
                <h3 className="text-sm font-extrabold text-white">Golden Luxury Captions</h3>
              </div>
            </div>
            <p className="text-xs text-slate-300 leading-relaxed font-medium mb-3">
              Subtitles rendered with restrained <strong>54px Outfit font</strong>, centered position, and smooth <strong>Fade In</strong> animation.
            </p>
            <div className="pt-3 border-t border-slate-800 flex flex-wrap gap-1.5 text-[10px] font-bold">
              <span className="bg-slate-800 text-amber-300 px-2 py-0.5 rounded-md border border-amber-400/20">Outfit 54px</span>
              <span className="bg-slate-800 text-amber-300 px-2 py-0.5 rounded-md border border-amber-400/20">Animation: Fade In</span>
              <span className="bg-slate-800 text-amber-300 px-2 py-0.5 rounded-md border border-amber-400/20">Position: Center</span>
            </div>
          </div>
        </div>

        {/* 14-Day Timeline Schedule Forecast */}
        <div className="bg-white rounded-2xl p-6 border border-slate-200/80 shadow-sm">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 mb-4">
            <div>
              <div className="flex items-center gap-2">
                <Calendar size={18} className="text-indigo-600" />
                <h3 className="text-base font-extrabold text-slate-900">14-Day Automation Timeline Forecast</h3>
              </div>
              <p className="text-xs text-slate-500 font-medium">
                Live simulation showing which product generates an image daily, and which receives a video reel every 3rd day.
              </p>
            </div>
            <div className="flex items-center gap-3 text-xs font-bold text-slate-500">
              <span className="flex items-center gap-1.5">
                <span className="w-2.5 h-2.5 rounded-full bg-violet-500 inline-block" /> Daily Image
              </span>
              <span className="flex items-center gap-1.5">
                <span className="w-2.5 h-2.5 rounded-full bg-amber-500 inline-block" /> 3-Day Video Reel
              </span>
            </div>
          </div>

          <div className="overflow-x-auto pb-2 scrollbar-thin">
            <div className="flex gap-2.5 min-w-max">
              {scheduleForecast.map((day) => (
                <div
                  key={day.dayIndex}
                  className={`w-36 p-3 rounded-xl border flex flex-col justify-between transition-all ${
                    day.isVideoDay
                      ? 'bg-amber-50/60 border-amber-300/80 shadow-sm shadow-amber-500/5'
                      : 'bg-slate-50/70 border-slate-200/80'
                  }`}
                >
                  <div>
                    <div className="flex items-center justify-between mb-1.5">
                      <span className="text-[11px] font-extrabold text-slate-900">{day.dayLabel}</span>
                      {day.isVideoDay && (
                        <span className="text-[9px] font-black uppercase tracking-wider px-1.5 py-0.2 rounded bg-amber-500 text-white shadow-xs">
                          Video Day
                        </span>
                      )}
                    </div>
                    <span className="text-[10px] text-slate-400 font-semibold block mb-2">{day.dateFormatted}</span>

                    {/* Image allocation */}
                    <div className="bg-white rounded-lg p-2 border border-slate-200/60 mb-2">
                      <span className="text-[9px] font-bold text-violet-600 flex items-center gap-1 uppercase tracking-wider">
                        <ImageIcon size={10} /> Image Poster
                      </span>
                      <span className="text-xs font-bold text-slate-800 truncate block mt-0.5" title={day.imageProduct?.title || 'None'}>
                        {day.imageProduct ? day.imageProduct.title : '—'}
                      </span>
                    </div>

                    {/* Video allocation */}
                    {day.isVideoDay ? (
                      <div className="bg-gradient-to-r from-amber-500 to-orange-500 text-white rounded-lg p-2 shadow-xs">
                        <span className="text-[9px] font-black uppercase tracking-wider flex items-center gap-1">
                          <Film size={10} /> Luxury Video
                        </span>
                        <span className="text-xs font-black truncate block mt-0.5" title={day.videoProduct?.title || 'None'}>
                          {day.videoProduct ? day.videoProduct.title : '—'}
                        </span>
                        {day.videoProduct && (
                          <span className="text-[9px] text-amber-100 font-bold block mt-0.5">
                            {day.videoProduct.duration}s · Golden Luxury
                          </span>
                        )}
                      </div>
                    ) : (
                      <div className="p-1.5 text-center text-[10px] font-semibold text-slate-400">
                        No video scheduled
                      </div>
                    )}
                  </div>

                  {day.dayIndex === 1 && (
                    <div className="mt-2 text-center text-[9px] font-extrabold text-amber-800 bg-amber-100/80 rounded py-0.5">
                      ⭐ Sequence Starts Here
                    </div>
                  )}
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Ordered Product Queue */}
        <div className="bg-white rounded-2xl border border-slate-200/80 shadow-sm overflow-hidden">
          <div className="p-5 sm:p-6 border-b border-slate-100 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
            <div>
              <div className="flex items-center gap-2">
                <Layers size={18} className="text-indigo-600" />
                <h2 className="text-base sm:text-lg font-black text-slate-900">
                  Ordered Round-Robin Products
                </h2>
                <span className="text-xs font-bold bg-slate-100 text-slate-600 px-2 py-0.5 rounded-full">
                  {queue.length} Total
                </span>
              </div>
              <p className="text-xs text-slate-500 font-medium mt-0.5">
                Use the Move Up (▲) and Move Down (▼) buttons to order your products. Generations cycle strictly in this order.
              </p>
            </div>

            {savingOrder && (
              <span className="inline-flex items-center gap-1.5 text-xs font-bold text-indigo-600 bg-indigo-50 px-3 py-1.5 rounded-xl border border-indigo-100">
                <RefreshCw size={12} className="animate-spin" /> Saving sequence...
              </span>
            )}
          </div>

          {loading ? (
            <div className="py-16 text-center text-slate-400 space-y-2">
              <RefreshCw size={24} className="animate-spin mx-auto text-indigo-600" />
              <p className="text-xs font-semibold">Loading automation queue...</p>
            </div>
          ) : queue.length === 0 ? (
            <div className="py-16 text-center text-slate-400 space-y-3">
              <div className="w-12 h-12 rounded-2xl bg-slate-100 text-slate-400 flex items-center justify-center mx-auto">
                <Layers size={24} />
              </div>
              <h3 className="text-sm font-bold text-slate-700">No Products in Automation Queue</h3>
              <p className="text-xs text-slate-500 max-w-sm mx-auto">
                Add your products to start automated round-robin image and video generation.
              </p>
              <button
                onClick={() => setShowAddModal(true)}
                className="bg-indigo-600 hover:bg-indigo-700 text-white font-bold text-xs py-2 px-4 rounded-xl transition-all inline-flex items-center gap-1.5 cursor-pointer"
              >
                <Plus size={14} /> Add First Product
              </button>
            </div>
          ) : (
            <div className="divide-y divide-slate-100">
              {queue.map((product, index) => {
                const isFirst = index === 0
                const isLast = index === queue.length - 1

                return (
                  <div
                    key={product.id}
                    className={`p-4 sm:p-5 flex flex-col md:flex-row md:items-center justify-between gap-4 transition-colors hover:bg-slate-50/60 ${
                      isFirst ? 'bg-amber-50/20' : ''
                    }`}
                  >
                    {/* Left: Ordering controls + Product Thumbnail & Info */}
                    <div className="flex items-center gap-4 min-w-0 flex-1">
                      {/* Move Up / Move Down buttons */}
                      <div className="flex flex-col items-center gap-1 shrink-0">
                        <button
                          type="button"
                          onClick={() => handleMoveProduct(index, index - 1)}
                          disabled={isFirst || savingOrder}
                          className={`p-1.5 rounded-lg border text-slate-600 transition-all ${
                            isFirst ? 'opacity-30 cursor-not-allowed border-slate-200' : 'hover:bg-indigo-50 hover:border-indigo-300 hover:text-indigo-600 border-slate-200 cursor-pointer active:scale-95'
                          }`}
                          title="Move Up in Rotation Order"
                        >
                          <ChevronUp size={16} />
                        </button>

                        <div className="w-8 h-8 rounded-xl bg-slate-900 text-white font-black text-xs flex items-center justify-center shadow-xs">
                          #{product.orderIndex}
                        </div>

                        <button
                          type="button"
                          onClick={() => handleMoveProduct(index, index + 1)}
                          disabled={isLast || savingOrder}
                          className={`p-1.5 rounded-lg border text-slate-600 transition-all ${
                            isLast ? 'opacity-30 cursor-not-allowed border-slate-200' : 'hover:bg-indigo-50 hover:border-indigo-300 hover:text-indigo-600 border-slate-200 cursor-pointer active:scale-95'
                          }`}
                          title="Move Down in Rotation Order"
                        >
                          <ChevronDown size={16} />
                        </button>
                      </div>

                      {/* Product Thumbnail */}
                      <div className="w-16 h-16 sm:w-20 sm:h-20 rounded-xl overflow-hidden bg-slate-100 border border-slate-200/80 shrink-0 relative">
                        {product.imageUrl ? (
                          <img
                            src={product.imageUrl}
                            alt={product.title}
                            className="w-full h-full object-cover"
                          />
                        ) : (
                          <div className="w-full h-full flex items-center justify-center text-slate-400">
                            <ImageIcon size={20} />
                          </div>
                        )}
                        {isFirst && (
                          <div className="absolute top-1 left-1 bg-amber-500 text-white text-[8px] font-black px-1.5 py-0.2 rounded shadow-xs uppercase">
                            1st Video
                          </div>
                        )}
                      </div>

                      {/* Details */}
                      <div className="min-w-0 flex-1">
                        <div className="flex items-center gap-2 flex-wrap">
                          <h4 className="text-sm font-extrabold text-slate-900 truncate" title={product.title}>
                            {product.title}
                          </h4>
                          {isFirst && (
                            <span className="text-[10px] font-bold bg-amber-100 text-amber-800 border border-amber-200 px-2 py-0.5 rounded-full flex items-center gap-1">
                              ⭐ Starts Video Sequence
                            </span>
                          )}
                          {product.price && (
                            <span className="text-[11px] font-bold text-slate-500">
                              · {product.price}
                            </span>
                          )}
                        </div>

                        <p className="text-xs text-slate-500 line-clamp-1 mt-0.5 font-medium">
                          {product.description || 'No description provided'}
                        </p>

                        {/* Generation counts & stats */}
                        <div className="flex items-center gap-3 mt-2 text-[11px] text-slate-500 font-semibold flex-wrap">
                          <span className="inline-flex items-center gap-1 text-violet-700 bg-violet-50 px-2 py-0.5 rounded-md border border-violet-100">
                            <ImageIcon size={11} /> {product.stats.imageCount} creatives generated
                          </span>
                          <span className="inline-flex items-center gap-1 text-amber-700 bg-amber-50 px-2 py-0.5 rounded-md border border-amber-200/80">
                            <Film size={11} /> {product.stats.videoCount} videos generated
                          </span>
                        </div>
                      </div>
                    </div>

                    {/* Right: Automation Toggles and Settings */}
                    <div className="flex flex-wrap items-center gap-3 md:gap-4 justify-between md:justify-end pt-3 md:pt-0 border-t md:border-t-0 border-slate-100">
                      {/* Daily Image Toggle */}
                      <div className="flex items-center gap-2 bg-slate-50 p-2 rounded-xl border border-slate-200/60">
                        <div className="text-right">
                          <span className="text-[10px] font-bold text-slate-500 block uppercase tracking-wider">Daily Image</span>
                          <span className="text-[11px] font-extrabold text-slate-800 block">
                            {product.autoGenerateDaily ? 'Active' : 'Paused'}
                          </span>
                        </div>
                        <button
                          type="button"
                          onClick={() => handleToggleDaily(product)}
                          className={`relative inline-flex h-5 w-10 flex-shrink-0 cursor-pointer rounded-full border-2 border-transparent transition-colors duration-200 ease-in-out focus:outline-none ${
                            product.autoGenerateDaily ? 'bg-violet-600' : 'bg-slate-300'
                          }`}
                        >
                          <span
                            className={`pointer-events-none inline-block h-4 w-4 transform rounded-full bg-white shadow-sm ring-0 transition duration-200 ease-in-out ${
                              product.autoGenerateDaily ? 'translate-x-5' : 'translate-x-0'
                            }`}
                          />
                        </button>
                      </div>

                      {/* Video Toggle (Every 3rd Day) */}
                      <div className="flex items-center gap-2 bg-amber-50/70 p-2 rounded-xl border border-amber-200/80">
                        <div className="text-right">
                          <span className="text-[10px] font-bold text-amber-700 block uppercase tracking-wider">3-Day Video</span>
                          <span className="text-[11px] font-extrabold text-amber-950 block">
                            {product.autoGenerateVideo ? `${product.videoSettings.duration}s Reel` : 'Paused'}
                          </span>
                        </div>
                        <button
                          type="button"
                          onClick={() => handleToggleVideo(product)}
                          className={`relative inline-flex h-5 w-10 flex-shrink-0 cursor-pointer rounded-full border-2 border-transparent transition-colors duration-200 ease-in-out focus:outline-none ${
                            product.autoGenerateVideo ? 'bg-amber-600' : 'bg-slate-300'
                          }`}
                        >
                          <span
                            className={`pointer-events-none inline-block h-4 w-4 transform rounded-full bg-white shadow-sm ring-0 transition duration-200 ease-in-out ${
                              product.autoGenerateVideo ? 'translate-x-5' : 'translate-x-0'
                            }`}
                          />
                        </button>
                      </div>

                      {/* Settings Button */}
                      <button
                        type="button"
                        onClick={() => handleOpenSettings(product)}
                        className="p-2.5 rounded-xl border border-slate-200 text-slate-600 hover:text-slate-900 hover:bg-slate-50 hover:border-slate-300 transition-all cursor-pointer flex items-center gap-1.5 text-xs font-bold"
                        title="Configure Video Duration & Custom Prompt"
                      >
                        <SlidersHorizontal size={14} />
                        <span className="hidden sm:inline">Settings</span>
                      </button>
                    </div>
                  </div>
                )
              })}
            </div>
          )}
        </div>
      </div>

      {/* Settings Modal */}
      {editingProduct && (
        <div className="fixed inset-0 z-[100] flex items-center justify-center p-4 sm:p-6 bg-slate-950/60 backdrop-blur-sm animate-in fade-in duration-200 overflow-y-auto">
          <div className="bg-white rounded-3xl max-w-lg w-full p-6 shadow-2xl border border-slate-100 flex flex-col my-auto max-h-[calc(100vh-3rem)] animate-in zoom-in-95 duration-200">
            <div className="flex items-start justify-between pb-3 border-b border-slate-100 shrink-0">
              <div>
                <span className="text-[10px] font-bold text-amber-600 uppercase tracking-wider block">Round-Robin Settings</span>
                <h3 className="text-lg font-black text-slate-900">
                  {editingProduct.title}
                </h3>
              </div>
              <button
                type="button"
                onClick={() => setEditingProduct(null)}
                className="p-1.5 rounded-xl text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition-colors cursor-pointer"
              >
                <X size={18} />
              </button>
            </div>

            <div className="overflow-y-auto py-4 space-y-5 pr-1">
              {/* Video Duration Selector */}
              <div className="space-y-2">
                <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider">
                  Video Reel Duration (Every 3rd Day)
                </label>
                <div className="grid grid-cols-4 gap-2">
                  {[15, 30, 45, 60].map((sec) => (
                    <button
                      key={sec}
                      type="button"
                      onClick={() => setModalDuration(sec)}
                      className={`py-3 rounded-2xl border text-xs font-bold transition-all flex flex-col items-center justify-center gap-0.5 cursor-pointer ${
                        modalDuration === sec
                          ? 'bg-amber-500 text-white border-amber-600 shadow-md shadow-amber-500/20'
                          : 'bg-slate-50 text-slate-700 border-slate-200 hover:bg-slate-100'
                      }`}
                    >
                      <span className="text-sm font-black">{sec}s</span>
                      <span className="text-[9px] opacity-80">{sec === 30 ? 'Default' : `${sec} seconds`}</span>
                    </button>
                  ))}
                </div>
              </div>

              {/* Captions Engine Specification */}
              <div className="bg-slate-900 text-white rounded-2xl p-4 space-y-2 border border-slate-800">
                <div className="flex items-center justify-between text-xs font-extrabold text-amber-400">
                  <span className="flex items-center gap-1.5">
                    <Sparkles size={14} /> Caption Engine (Remotion)
                  </span>
                  <span className="bg-amber-400 text-slate-950 text-[10px] px-2 py-0.5 rounded-md font-black uppercase">
                    Golden Luxury
                  </span>
                </div>
                <div className="grid grid-cols-3 gap-2 text-[11px] pt-1 border-t border-slate-800">
                  <div>
                    <span className="text-slate-400 text-[10px] block">Animation</span>
                    <span className="font-bold text-slate-200">Fade In</span>
                  </div>
                  <div>
                    <span className="text-slate-400 text-[10px] block">Position</span>
                    <span className="font-bold text-slate-200">Center (Reel)</span>
                  </div>
                  <div>
                    <span className="text-slate-400 text-[10px] block">Font</span>
                    <span className="font-bold text-slate-200">Outfit 54px</span>
                  </div>
                </div>
              </div>

              {/* Custom Prompt / Creative Direction */}
              <div className="space-y-1.5">
                <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider">
                  Product-Specific Creative Direction (Optional)
                </label>
                <textarea
                  value={modalCustomPrompt}
                  onChange={(e) => setModalCustomPrompt(e.target.value)}
                  placeholder="e.g. Prime Rohini Sector 24 location, 110 gaj 3 BHK builder floors, lift and parking, 1 km to Rithala Metro..."
                  rows={3}
                  className="w-full p-3 rounded-2xl bg-slate-50 border border-slate-200 text-xs text-slate-900 font-medium focus:ring-2 focus:ring-amber-500/20 focus:border-amber-500 outline-none transition-all resize-none"
                />
                <span className="text-[10px] text-slate-400 font-medium block">
                  Leave empty to use automatic AI optimal copy and styling.
                </span>
              </div>
            </div>

            {/* Action buttons */}
            <div className="flex items-center justify-end gap-2 pt-3 border-t border-slate-100 shrink-0">
              <button
                type="button"
                onClick={() => setEditingProduct(null)}
                className="px-4 py-2.5 rounded-xl text-xs font-bold text-slate-500 hover:text-slate-800 hover:bg-slate-100 transition-colors cursor-pointer"
              >
                Cancel
              </button>
              <button
                type="button"
                onClick={handleSaveSettings}
                disabled={isSavingSettings}
                className="bg-slate-900 hover:bg-slate-800 text-white font-bold text-xs py-2.5 px-5 rounded-xl shadow-md transition-all flex items-center gap-1.5 cursor-pointer disabled:opacity-50"
              >
                {isSavingSettings ? (
                  <>
                    <RefreshCw size={13} className="animate-spin" /> Saving...
                  </>
                ) : (
                  <>
                    <Check size={14} /> Save Specifications
                  </>
                )}
              </button>
            </div>
          </div>
        </div>
      )}

      {/* Add Product Modal */}
      {showAddModal && (
        <div className="fixed inset-0 z-[100] flex items-center justify-center p-4 sm:p-6 bg-slate-950/60 backdrop-blur-sm animate-in fade-in duration-200 overflow-y-auto">
          <div className="bg-white rounded-3xl max-w-lg w-full p-6 shadow-2xl border border-slate-100 flex flex-col my-auto max-h-[calc(100vh-3rem)] animate-in zoom-in-95 duration-200">
            <div className="flex items-start justify-between pb-3 border-b border-slate-100 shrink-0">
              <div>
                <span className="text-[10px] font-bold text-indigo-600 uppercase tracking-wider block">Queue Enrollment</span>
                <h3 className="text-lg font-black text-slate-900">
                  Add Product to Automation
                </h3>
              </div>
              <button
                type="button"
                onClick={() => setShowAddModal(false)}
                className="p-1.5 rounded-xl text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition-colors cursor-pointer"
              >
                <X size={18} />
              </button>
            </div>

            <div className="overflow-y-auto py-4 space-y-3 pr-1">
              <div>
                <label className="block text-[10px] font-bold text-slate-500 uppercase tracking-widest mb-1">
                  Product / Property Title
                </label>
                <input
                  type="text"
                  value={newTitle}
                  onChange={(e) => setNewTitle(e.target.value)}
                  placeholder="e.g. Umang Residency 3 BHK"
                  className="w-full p-3 rounded-xl bg-slate-50 border border-slate-200 text-xs font-bold text-slate-900 outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
                />
              </div>

              <div>
                <label className="block text-[10px] font-bold text-slate-500 uppercase tracking-widest mb-1">
                  Product Details / Features
                </label>
                <textarea
                  value={newDescription}
                  onChange={(e) => setNewDescription(e.target.value)}
                  placeholder="e.g. Freehold builder floors, lift, reserved parking, prime location..."
                  rows={3}
                  className="w-full p-3 rounded-xl bg-slate-50 border border-slate-200 text-xs font-medium text-slate-900 outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500 resize-none"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-[10px] font-bold text-slate-500 uppercase tracking-widest mb-1">
                    Price (Optional)
                  </label>
                  <input
                    type="text"
                    value={newPrice}
                    onChange={(e) => setNewPrice(e.target.value)}
                    placeholder="e.g. ₹65 Lakhs"
                    className="w-full p-3 rounded-xl bg-slate-50 border border-slate-200 text-xs font-semibold text-slate-900 outline-none focus:ring-2 focus:ring-indigo-500/20"
                  />
                </div>
                <div>
                  <label className="block text-[10px] font-bold text-slate-500 uppercase tracking-widest mb-1">
                    Video Reel Duration
                  </label>
                  <select
                    value={newDuration}
                    onChange={(e) => setNewDuration(Number(e.target.value))}
                    className="w-full p-3 rounded-xl bg-slate-50 border border-slate-200 text-xs font-bold text-slate-900 outline-none"
                  >
                    <option value={15}>15 Seconds</option>
                    <option value={30}>30 Seconds (Default)</option>
                    <option value={45}>45 Seconds</option>
                    <option value={60}>60 Seconds</option>
                  </select>
                </div>
              </div>

              <div>
                <label className="block text-[10px] font-bold text-slate-500 uppercase tracking-widest mb-1">
                  Reference Image URL (Optional)
                </label>
                <input
                  type="text"
                  value={newImageUrl}
                  onChange={(e) => setNewImageUrl(e.target.value)}
                  placeholder="https://..."
                  className="w-full p-3 rounded-xl bg-slate-50 border border-slate-200 text-xs font-medium text-slate-900 outline-none"
                />
              </div>
            </div>

            <div className="flex items-center justify-end gap-2 pt-3 border-t border-slate-100 shrink-0">
              <button
                type="button"
                onClick={() => setShowAddModal(false)}
                className="px-4 py-2.5 rounded-xl text-xs font-bold text-slate-500 hover:text-slate-800 hover:bg-slate-100 transition-colors cursor-pointer"
              >
                Cancel
              </button>
              <button
                type="button"
                onClick={handleCreateProduct}
                disabled={isCreatingProduct}
                className="bg-indigo-600 hover:bg-indigo-700 text-white font-bold text-xs py-2.5 px-5 rounded-xl shadow-md transition-all flex items-center gap-1.5 cursor-pointer disabled:opacity-50"
              >
                {isCreatingProduct ? (
                  <>
                    <RefreshCw size={13} className="animate-spin" /> Adding...
                  </>
                ) : (
                  <>
                    <Check size={14} /> Add to Round-Robin
                  </>
                )}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  )
}
