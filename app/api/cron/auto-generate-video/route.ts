/* eslint-disable @typescript-eslint/no-explicit-any --
 * Rows come back untyped from Supabase (the generated database.types.ts is
 * stale), so provider payloads and row shapes are handled as `any` here — the
 * same convention utils/credits.ts and utils/voice-helper.ts follow.
 */
import { NextResponse } from 'next/server';
import { createClient } from '@supabase/supabase-js';
import { createGrokVideoTask, createGeminiTTS } from '@/utils/external-apis';
import { ensureJpegImage } from '@/utils/image-converter';
import { z } from 'zod';
import { generateObject } from 'ai';
import { google } from '@ai-sdk/google';

export const dynamic = 'force-dynamic';
export const fetchCache = 'force-no-store';
export const revalidate = 0;
export const maxDuration = 300;

const supabaseAdmin = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY!
);

function parseConfigurations(config: any): any {
  if (!config) return {};
  if (typeof config === 'object') return config;
  try {
    return JSON.parse(config);
  } catch (e) {
    return {};
  }
}

export async function GET(request: Request) {
  return handleVideoAutoGenerateDispatcher(request);
}

export async function POST(request: Request) {
  return handleVideoAutoGenerateDispatcher(request);
}

async function handleVideoAutoGenerateDispatcher(request: Request) {
  try {
    const url = new URL(request.url);
    const authHeader = request.headers.get('authorization');
    const token = authHeader ? authHeader.replace(/^Bearer\s+/i, '').trim() : '';
    const cronSecret = url.searchParams.get('cronSecret')?.trim() || token || null;
    const expectedSecret = process.env.CRON_SECRET ? process.env.CRON_SECRET.trim() : '';

    if (expectedSecret && cronSecret !== expectedSecret) {
      console.warn('[Video Auto-Gen Dispatcher] Unauthorized access attempt.');
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }

    const isForce = url.searchParams.get('force') === 'true';
    const targetUserId = url.searchParams.get('userId');

    // 1. Fetch properties that have auto_gen_video enabled in configurations
    let propQuery = supabaseAdmin
      .from('properties')
      .select('id, title, description, price, image_url, images, user_id, configurations, created_at');

    if (targetUserId) {
      propQuery = propQuery.eq('user_id', targetUserId);
    }

    const { data: allProps, error: propErr } = await propQuery;
    if (propErr) throw propErr;

    // Filter properties where configurations->auto_gen_video === true
    const videoProps = (allProps || []).filter(p => {
      const cfg = parseConfigurations(p.configurations);
      return cfg.auto_gen_video === true || cfg.auto_gen_video === 'true';
    });

    if (videoProps.length === 0) {
      return NextResponse.json({ message: 'No properties enrolled in video round-robin automation' });
    }

    // Group properties by user_id
    const userPropertiesMap: Record<string, typeof videoProps> = {};
    videoProps.forEach(p => {
      if (!userPropertiesMap[p.user_id]) userPropertiesMap[p.user_id] = [];
      userPropertiesMap[p.user_id].push(p);
    });

    const now = new Date();
    const forwardedHost = request.headers.get('x-forwarded-host');
    const forwardedProto = request.headers.get('x-forwarded-proto') || 'https';
    let baseUrl = `${url.origin}`;
    if (forwardedHost && !forwardedHost.includes('localhost') && !forwardedHost.includes('local.')) {
      baseUrl = `${forwardedProto}://${forwardedHost}`;
    } else if (process.env.NEXT_PUBLIC_APP_URL && !process.env.NEXT_PUBLIC_APP_URL.includes('localhost')) {
      baseUrl = process.env.NEXT_PUBLIC_APP_URL;
    } else {
      baseUrl = 'https://app.nobogent.com';
    }

    const triggeredVideos: any[] = [];

    // Tenant automation policy: master switch, per-feature toggle, cadence days.
    const { data: videoPolicies } = await supabaseAdmin
      .from('tenant_automations')
      .select('user_id, master_enabled, video_reel, video_cadence_days, bill_automation');
    const videoPolicyByTenant = new Map<string, any>();
    for (const p of videoPolicies || []) videoPolicyByTenant.set(p.user_id, p);

    // 2. Process each user's video cadence
    for (const [userId, userProps] of Object.entries(userPropertiesMap)) {
      const videoPolicy = videoPolicyByTenant.get(userId);
      if (videoPolicy && (!videoPolicy.master_enabled || !videoPolicy.video_reel)) {
        console.log(`[Video Auto-Gen] Disabled by automation policy for user ${userId}. Skipping.`);
        continue;
      }
      const cadenceDays = Math.max(1, Number(videoPolicy?.video_cadence_days ?? 3));

      // Fetch user profile
      const { data: profile } = await supabaseAdmin
        .from('profiles')
        .select('id, business_name, business_info, client_features, whatsapp_personal_number, contact_number, email')
        .eq('id', userId)
        .single();

      if (!profile) continue;

      // Sort userProps by round_robin_order
      const savedOrder: string[] = Array.isArray(profile.client_features?.creation_round_robin_order)
        ? profile.client_features.creation_round_robin_order
        : [];

      userProps.sort((a, b) => {
        const aCfg = parseConfigurations(a.configurations);
        const bCfg = parseConfigurations(b.configurations);
        const aIdx = savedOrder.indexOf(a.id) !== -1 ? savedOrder.indexOf(a.id) : (aCfg.round_robin_order || 999);
        const bIdx = savedOrder.indexOf(b.id) !== -1 ? savedOrder.indexOf(b.id) : (bCfg.round_robin_order || 999);
        return aIdx - bIdx;
      });

      // Latest AUTOMATED video belonging to an ENROLLED property.
      // Manual videos (and assets with property_id = null) must not perturb the
      // rotation — previously a null/unenrolled property_id made findIndex
      // return -1 and the rotation silently restarted at property #1 forever.
      const { data: latestVideoAssets } = await supabaseAdmin
        .from('assets')
        .select('id, property_id, created_at, type, url, metadata')
        .eq('user_id', userId)
        .eq('type', 'video')
        .order('created_at', { ascending: false })
        .limit(25);

      const enrolledIds = new Set(userProps.map((p) => p.id));
      const lastVideo = (latestVideoAssets || []).find(
        (a: any) => a.property_id && enrolledIds.has(a.property_id)
      ) || null;

      // Check the tenant's cadence (default 3 days)
      let daysSinceLastVideo = 99;
      if (lastVideo?.created_at) {
        const diffMs = now.getTime() - new Date(lastVideo.created_at).getTime();
        daysSinceLastVideo = Math.floor(diffMs / (1000 * 60 * 60 * 24));
      }

      const isVideoDue = isForce || daysSinceLastVideo >= cadenceDays || !lastVideo;

      if (!isVideoDue) {
        console.log(`[Video Auto-Gen] Video for user ${userId} not due yet (${daysSinceLastVideo}/${cadenceDays} days elapsed). Skipping.`);
        continue;
      }

      // Advance exactly one step in the saved round-robin order.
      let targetProduct = userProps[0];
      if (lastVideo?.property_id && userProps.length > 1) {
        const lastIdx = userProps.findIndex(p => p.id === lastVideo.property_id);
        if (lastIdx !== -1) {
          targetProduct = userProps[(lastIdx + 1) % userProps.length];
        }
      }

      console.log(`[Video Auto-Gen] 🎬 Triggering 3-day video for "${targetProduct.title}" (User: ${profile.business_name || userId})...`);

      const targetCfg = parseConfigurations(targetProduct.configurations);
      const videoSettings = targetCfg.auto_gen_video_settings || {};
      // "30 second" commercial = N clips of 15s, stitched later by
      // /api/video/callback. A single 30s request is ILLEGAL for this provider:
      // bytedance/seedance-2-mini accepts 4-15 seconds only, and a rejection
      // produced no rows and a misleading 200.
      const requestedDuration = Number(videoSettings.duration) || 30;
      const clipSeconds = 15;
      const requiredClips = Math.max(1, Math.min(4, Math.round(requestedDuration / clipSeconds)));
      const duration = requestedDuration;
      const customPrompt = (videoSettings.custom_prompt || '').trim();

      // Credit gate before spending on the video provider. Balance-only — see
      // lib/automation/billing.ts for why hasEnoughCredits() is unsuitable.
      const shouldBill = videoPolicy?.bill_automation !== false;
      if (shouldBill) {
        try {
          const { canAffordAutomation } = await import('@/lib/automation/billing');
          const { CREDIT_COSTS } = await import('@/utils/credits');
          const needed = requiredClips * CREDIT_COSTS.AI_VIDEO_15SEC_CHUNK;
          const afford = await canAffordAutomation(supabaseAdmin, userId, needed);
          if (!afford.ok) {
            console.log(`[Video Auto-Gen] Insufficient credits for ${userId} (needs ${needed}, has ${afford.balance}). Skipping.`);
            continue;
          }
        } catch (creditErr: any) {
          console.warn('[Video Auto-Gen] credit check failed:', creditErr?.message);
        }
      }

      // Golden Luxury Caption Specifications (Outfit font, 54px restrained, Fade in, Center position)
      const captionTheme = 'goldenLuxury';

      // 3. Generate High-Converting Commercial Script via Gemini
      const videoSchema = z.object({
        videoPrompts: z.array(z.string()).describe(`Exactly ${requiredClips} prompts, one per ${clipSeconds}-second clip, in order`),
        finalCaption: z.string(),
        hookLine: z.string(),
        // Spoken script. Needed because Grok Imagine renders visuals but does not
        // voice the dialogue, so a non-avatar commercial must get TTS.
        dialogue: z.string()
      });

      const videoGenPrompt = `You are a world-class luxury commercial director creating a ${duration}-second 9:16 vertical commercial reel.
Business: "${profile.business_name || 'Nobogent'}"
Product: "${targetProduct.title}"
Description: "${targetProduct.description || ''}"
Price: "${targetProduct.price || 'Contact for Exclusive Access'}"
Total length: ${duration} seconds, delivered as EXACTLY ${requiredClips} clip(s) of ${clipSeconds} seconds each — return one videoPrompts entry per clip, in order, continuing the same location and presenter.
${customPrompt ? `Client Creative Direction: "${customPrompt}"` : ''}

Output a structured video prompt for the Grok Imagine 1.5 video engine with exact uppercase headers:
LOCATION (Luxury setting)
CHARACTER APPEARANCE (Photorealistic presenter interacting naturally with the property, consistent across every clip)
DIALOGUE (Spoken script fitting exactly ${clipSeconds} seconds per clip: ~${Math.round(clipSeconds * 2.2)} words each. If India context, write in natural conversational Hinglish).
SPEECH STYLE (Confident, warm, prestigious)
ACTION (Dynamic presenter movement, showing key features)
B-ROLL (Cinematic cutaways of interior, architectural brilliance)
CAMERA (Smooth steadicam tracking, shallow depth of field)
LIGHTING (Warm architectural golden hour)
STYLE (High-budget commercial aesthetic)
AVOID (Do not mention phone numbers in dialogue)`;

      try {
        const { object: vidObj } = await generateObject({
          model: google('gemini-3.5-flash'),
          schema: videoSchema,
          prompt: videoGenPrompt
        });

        // 4. Submit ONE PROVIDER TASK PER CLIP (provider caps duration at 15s).
        const prompts: string[] = (vidObj.videoPrompts || []).filter(Boolean).slice(0, requiredClips);
        while (prompts.length < requiredClips) {
          prompts.push(prompts[0] || `Cinematic ${clipSeconds}-second vertical commercial clip for ${targetProduct.title}`);
        }

        // SAME PIPELINE AS THE CREATION TAB.
        // Grok Imagine 1.5 via createGrokVideoTask — the identical provider helper
        // the manual path uses. Seedance must NOT be used here:
        // app/api/video/generate/route.ts:512 says "Non-avatar videos strictly use
        // Grok Imagine 1.5 (Seedance is completely prohibited to avoid high costs)".
        // This route previously submitted bytedance/seedance-2-mini, contradicting
        // that policy.
        const imageUrls: string[] = [];
        const rawImages: string[] = Array.isArray((targetProduct as any).images) && (targetProduct as any).images.length
          ? (targetProduct as any).images.slice(0, 3)
          : (targetProduct.image_url ? [targetProduct.image_url] : []);
        for (const img of rawImages) {
          try {
            const converted = await ensureJpegImage(img, userId);
            if (converted) imageUrls.push(converted);
          } catch (e) {}
        }

        // TTS voiceover.
        // Grok Imagine 1.5 renders the visuals but does not speak the dialogue, so
        // a NON-AVATAR commercial needs its own voice track. Automation never uses
        // an avatar presenter, therefore TTS is always required here. The manual
        // path does the same thing (app/api/video/generate/route.ts:989-1011) and
        // marks the pending audio as `tts:<taskId>` for the callback to resolve.
        let grokAudioUrl: string | null = null;
        const dialogueText = String((vidObj as any).dialogue || '').trim();
        if (dialogueText.length > 10) {
          try {
            const tts = await createGeminiTTS({
              dialogueText,
              speakerName: 'Aoede',
              callBackUrl: `${baseUrl}/api/video/callback`,
            });
            if ((tts as any)?.taskId) grokAudioUrl = `tts:${(tts as any).taskId}`;
          } catch (ttsErr: any) {
            console.warn('[Video Auto-Gen] TTS failed, video will be silent:', ttsErr?.message);
          }
        }

        const callbackUrl = `${baseUrl}/api/video/callback`;
        const submitted: Array<{ index: number; taskId: string }> = [];
        for (let i = 0; i < prompts.length; i++) {
          const clipResult = await createGrokVideoTask({
            prompt: prompts[i],
            imageUrls: imageUrls.length ? imageUrls : undefined,
            aspectRatio: '9:16',
            resolution: '480p',
            duration: clipSeconds,
            callBackUrl: callbackUrl,
          });
          if (!clipResult?.taskId) {
            console.error(`[Video Auto-Gen] Grok clip ${i + 1}/${prompts.length} submit failed:`, clipResult?.error);
            break;
          }
          submitted.push({ index: i, taskId: clipResult.taskId });
        }

        if (submitted.length === 0) {
          console.error(`[Video Auto-Gen] No clips submitted for "${targetProduct.title}" — skipping.`);
          continue;
        }

        {
          // 5. Insert Asset & one video_tasks row PER CLIP.
          // The callback waits for every sibling sharing asset_id before stitching.
          const { data: newAsset } = await supabaseAdmin
            .from('assets')
            .insert({
              user_id: userId,
              property_id: targetProduct.id,
              type: 'video',
              status: 'Processing',
              url: 'https://designs.adrolls.in/processing',
              caption: vidObj.finalCaption,
              metadata: {
                auto_generated: true,
                duration,
                clips: submitted.length,
                clip_seconds: clipSeconds,
                caption_theme: captionTheme,
                caption_style: {
                  style: 'goldenLuxury',
                  animation: 'fade',
                  position: 'center',
                  fontFamily: 'Outfit',
                  fontSize: 54
                },
                cadence_days: cadenceDays,
                instructions: customPrompt || undefined
              },
              created_at: new Date().toISOString()
            })
            .select()
            .single();

          if (newAsset) {
            // Mirrors the manual path's video_tasks contract
            // (app/api/video/generate/route.ts): the FULL prompts array plus
            // current_index so the callback's retry logic can re-read this clip's
            // prompt, and video_model 'grok' so the callback drives the right
            // provider branch.
            const taskRows = submitted.map((s) => ({
              user_id: userId,
              property_id: targetProduct.id,
              asset_id: newAsset.id,
              prompts,
              current_index: s.index,
              last_task_id: s.taskId,
              last_successful_task_id: imageUrls[0] || null,
              aspect_ratio: '9:16',
              status: 'Processing',
              video_model: 'grok',
              audio_url: grokAudioUrl,
              final_caption: vidObj.finalCaption
            }));
            const { error: taskErr } = await supabaseAdmin.from('video_tasks').insert(taskRows);
            if (taskErr) {
              console.error('[Video Auto-Gen] video_tasks insert failed:', taskErr.message);
            }

            // Charge per successfully submitted clip. Done after acceptance so a
            // rejected submission costs the tenant nothing. Uses
            // charge_automation(), which has no subscription gate (see
            // 20261111190000_charge_automation.sql). Failures are refunded by
            // /api/video/callback at AI_VIDEO_15SEC_CHUNK per clip.
            if (shouldBill && submitted.length > 0) {
              try {
                const { CREDIT_COSTS } = await import('@/utils/credits');
                const { data: charge, error: chargeErr } = await supabaseAdmin.rpc('charge_automation', {
                  p_user_id: userId,
                  p_amount: submitted.length * CREDIT_COSTS.AI_VIDEO_15SEC_CHUNK,
                  p_description: `Auto video (${submitted.length} x ${clipSeconds}s) — ${targetProduct.title}`,
                  p_category: 'ai_generation',
                });
                if (chargeErr) console.warn('[Video Auto-Gen] charge failed:', chargeErr.message);
                else if (!charge?.charged) console.log('[Video Auto-Gen] not charged:', JSON.stringify(charge));
              } catch (creditErr: any) {
                console.warn('[Video Auto-Gen] credit deduction failed:', creditErr?.message);
              }
            }
          }

          triggeredVideos.push({
            userId,
            businessName: profile.business_name,
            productTitle: targetProduct.title,
            duration,
            clips: submitted.length,
            taskIds: submitted.map((s) => s.taskId),
            captionTheme
          });

          console.log(`[Video Auto-Gen] ✅ Dispatched ${submitted.length}-clip ${duration}s video for "${targetProduct.title}" (asset: ${newAsset?.id})`);
        }
      } catch (genErr: any) {
        console.error(`[Video Auto-Gen] Error generating video for ${targetProduct.title}:`, genErr);
      }
    }

    return NextResponse.json({
      success: true,
      cadence: 'every_3rd_day',
      triggeredCount: triggeredVideos.length,
      triggeredVideos
    });

  } catch (error: any) {
    console.error('❌ [Video Auto-Gen Dispatcher] Error:', error);
    return NextResponse.json({ error: error.message || 'Video auto-gen failed' }, { status: 500 });
  }
}
