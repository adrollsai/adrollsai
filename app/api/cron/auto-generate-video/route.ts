import { NextResponse } from 'next/server';
import { createClient } from '@supabase/supabase-js';
import { createKieTask, generateKieChat } from '@/utils/external-apis';
import { ensureJpegImage } from '@/utils/image-converter';
import { z } from 'zod';
import { generateObject } from 'ai';
import { google } from '@ai-sdk/google';

export const dynamic = 'force-dynamic';
export const fetchCache = 'force-no-store';
export const revalidate = 0;
export const maxDuration = 300;

const supabaseAdmin = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY!
);

function parseConfigurations(config: any): any {
  if (!config) return {};
  if (typeof config === 'object') return config;
  try {
    return JSON.parse(config);
  } catch (e) {
    return {};
  }
}

export async function GET(request: Request) {
  return handleVideoAutoGenerateDispatcher(request);
}

export async function POST(request: Request) {
  return handleVideoAutoGenerateDispatcher(request);
}

async function handleVideoAutoGenerateDispatcher(request: Request) {
  try {
    const url = new URL(request.url);
    const authHeader = request.headers.get('authorization');
    const token = authHeader ? authHeader.replace(/^Bearer\s+/i, '').trim() : '';
    const cronSecret = url.searchParams.get('cronSecret')?.trim() || token || null;
    const expectedSecret = process.env.CRON_SECRET ? process.env.CRON_SECRET.trim() : '';

    if (expectedSecret && cronSecret !== expectedSecret) {
      console.warn('[Video Auto-Gen Dispatcher] Unauthorized access attempt.');
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }

    const isForce = url.searchParams.get('force') === 'true';
    const targetUserId = url.searchParams.get('userId');

    // 1. Fetch properties that have auto_gen_video enabled in configurations
    let propQuery = supabaseAdmin
      .from('properties')
      .select('id, title, description, price, image_url, images, user_id, configurations, created_at');

    if (targetUserId) {
      propQuery = propQuery.eq('user_id', targetUserId);
    }

    const { data: allProps, error: propErr } = await propQuery;
    if (propErr) throw propErr;

    // Filter properties where configurations->auto_gen_video === true
    const videoProps = (allProps || []).filter(p => {
      const cfg = parseConfigurations(p.configurations);
      return cfg.auto_gen_video === true || cfg.auto_gen_video === 'true';
    });

    if (videoProps.length === 0) {
      return NextResponse.json({ message: 'No properties enrolled in video round-robin automation' });
    }

    // Group properties by user_id
    const userPropertiesMap: Record<string, typeof videoProps> = {};
    videoProps.forEach(p => {
      if (!userPropertiesMap[p.user_id]) userPropertiesMap[p.user_id] = [];
      userPropertiesMap[p.user_id].push(p);
    });

    const now = new Date();
    const forwardedHost = request.headers.get('x-forwarded-host');
    const forwardedProto = request.headers.get('x-forwarded-proto') || 'https';
    let baseUrl = `${url.origin}`;
    if (forwardedHost && !forwardedHost.includes('localhost') && !forwardedHost.includes('local.')) {
      baseUrl = `${forwardedProto}://${forwardedHost}`;
    } else if (process.env.NEXT_PUBLIC_APP_URL && !process.env.NEXT_PUBLIC_APP_URL.includes('localhost')) {
      baseUrl = process.env.NEXT_PUBLIC_APP_URL;
    } else {
      baseUrl = 'https://app.nobogent.com';
    }

    const triggeredVideos: any[] = [];

    // 2. Process each user's 3-day video cadence
    for (const [userId, userProps] of Object.entries(userPropertiesMap)) {
      // Fetch user profile
      const { data: profile } = await supabaseAdmin
        .from('profiles')
        .select('id, business_name, business_info, client_features, whatsapp_personal_number, contact_number, email')
        .eq('id', userId)
        .single();

      if (!profile) continue;

      // Sort userProps by round_robin_order
      const savedOrder: string[] = Array.isArray(profile.client_features?.creation_round_robin_order)
        ? profile.client_features.creation_round_robin_order
        : [];

      userProps.sort((a, b) => {
        const aCfg = parseConfigurations(a.configurations);
        const bCfg = parseConfigurations(b.configurations);
        const aIdx = savedOrder.indexOf(a.id) !== -1 ? savedOrder.indexOf(a.id) : (aCfg.round_robin_order || 999);
        const bIdx = savedOrder.indexOf(b.id) !== -1 ? savedOrder.indexOf(b.id) : (bCfg.round_robin_order || 999);
        return aIdx - bIdx;
      });

      // Fetch the latest generated video asset for this user
      const { data: latestVideoAssets } = await supabaseAdmin
        .from('assets')
        .select('id, property_id, created_at, type, url')
        .eq('user_id', userId)
        .or('type.eq.video,url.ilike.%.mp4')
        .order('created_at', { ascending: false })
        .limit(1);

      const lastVideo = latestVideoAssets && latestVideoAssets.length > 0 ? latestVideoAssets[0] : null;

      // Check 3-day cadence
      let daysSinceLastVideo = 99;
      if (lastVideo?.created_at) {
        const diffMs = now.getTime() - new Date(lastVideo.created_at).getTime();
        daysSinceLastVideo = Math.floor(diffMs / (1000 * 60 * 60 * 24));
      }

      const isVideoDue = isForce || daysSinceLastVideo >= 3 || !lastVideo;

      if (!isVideoDue) {
        console.log(`[Video Auto-Gen] Video for user ${userId} not due yet (${daysSinceLastVideo}/3 days elapsed). Skipping.`);
        continue;
      }

      // Determine next product in sequence:
      // If no last video: START FROM THE FIRST PRODUCT (Product #1) as requested!
      let targetProduct = userProps[0];
      if (lastVideo?.property_id && userProps.length > 1) {
        const lastIdx = userProps.findIndex(p => p.id === lastVideo.property_id);
        if (lastIdx !== -1) {
          const nextIdx = (lastIdx + 1) % userProps.length;
          targetProduct = userProps[nextIdx];
        }
      }

      console.log(`[Video Auto-Gen] 🎬 Triggering 3-day video for "${targetProduct.title}" (User: ${profile.business_name || userId})...`);

      const targetCfg = parseConfigurations(targetProduct.configurations);
      const videoSettings = targetCfg.auto_gen_video_settings || {};
      const duration = Number(videoSettings.duration) || 30;
      const customPrompt = (videoSettings.custom_prompt || '').trim();

      // Golden Luxury Caption Specifications (Outfit font, 54px restrained, Fade in, Center position)
      const captionTheme = 'goldenLuxury';

      // 3. Generate High-Converting Commercial Script via Gemini
      const videoSchema = z.object({
        videoPrompt: z.string(),
        finalCaption: z.string(),
        hookLine: z.string()
      });

      const videoGenPrompt = `You are a world-class luxury commercial director creating a ${duration}-second 9:16 vertical commercial reel.
Business: "${profile.business_name || 'Nobogent'}"
Product: "${targetProduct.title}"
Description: "${targetProduct.description || ''}"
Price: "${targetProduct.price || 'Contact for Exclusive Access'}"
Duration: ${duration} seconds.
${customPrompt ? `Client Creative Direction: "${customPrompt}"` : ''}

Output a structured video prompt for Seedance mini video engine with exact uppercase headers:
LOCATION (Luxury setting)
CHARACTER APPEARANCE (Photorealistic presenter interacting naturally with property/product)
DIALOGUE (Spoken script fitting exactly ${duration} seconds: ~${Math.round(duration * 2.2)} words. If India context, write in natural conversational Hinglish).
SPEECH STYLE (Confident, warm, prestigious)
ACTION (Dynamic presenter movement, showing key features)
B-ROLL (Cinematic cutaways of interior, architectural brilliance)
CAMERA (Smooth steadicam tracking, shallow depth of field)
LIGHTING (Warm architectural golden hour)
STYLE (High-budget commercial aesthetic)
AVOID (Do not mention phone numbers in dialogue)`;

      try {
        const { object: vidObj } = await generateObject({
          model: google('gemini-3.5-flash'),
          schema: videoSchema,
          prompt: videoGenPrompt
        });

        // 4. Submit Task to Kie AI Seedance 2 Mini
        const videoPayload: any = {
          model: 'bytedance/seedance-2-mini',
          callBackUrl: `${baseUrl}/api/video/callback`,
          input: {
            prompt: vidObj.videoPrompt,
            aspect_ratio: '9:16',
            duration: duration <= 15 ? 15 : 30,
            generate_audio: true,
            resolution: '480p',
            nsfw_checker: true,
            web_search: false
          }
        };

        if (targetProduct.image_url) {
          try {
            const convertedImg = await ensureJpegImage(targetProduct.image_url, userId);
            videoPayload.input.reference_image_urls = [convertedImg];
          } catch (e) {}
        }

        const taskResult = await createKieTask(videoPayload);

        if (taskResult?.taskId) {
          // 5. Insert Asset & video_tasks records
          const { data: newAsset } = await supabaseAdmin
            .from('assets')
            .insert({
              user_id: userId,
              property_id: targetProduct.id,
              type: 'video',
              status: 'Processing',
              url: 'https://designs.adrolls.in/processing',
              caption: vidObj.finalCaption,
              metadata: {
                auto_generated: true,
                duration,
                caption_theme: captionTheme,
                caption_style: {
                  style: 'goldenLuxury',
                  animation: 'fade',
                  position: 'center',
                  fontFamily: 'Outfit',
                  fontSize: 54
                },
                cadence: 'every_3rd_day',
                instructions: customPrompt || undefined
              },
              created_at: new Date().toISOString()
            })
            .select()
            .single();

          if (newAsset) {
            await supabaseAdmin.from('video_tasks').insert([{
              user_id: userId,
              property_id: targetProduct.id,
              asset_id: newAsset.id,
              prompts: [vidObj.videoPrompt],
              current_index: 0,
              last_task_id: taskResult.taskId,
              last_successful_task_id: '',
              aspect_ratio: '9:16',
              status: 'Processing',
              final_caption: vidObj.finalCaption
            }]);
          }

          triggeredVideos.push({
            userId,
            businessName: profile.business_name,
            productTitle: targetProduct.id,
            duration,
            taskId: taskResult.taskId,
            captionTheme
          });

          console.log(`[Video Auto-Gen] ✅ Successfully dispatched 3-day video task for "${targetProduct.title}" (Asset: ${newAsset?.id})`);
        }
      } catch (genErr: any) {
        console.error(`[Video Auto-Gen] Error generating video for ${targetProduct.title}:`, genErr);
      }
    }

    return NextResponse.json({
      success: true,
      cadence: 'every_3rd_day',
      triggeredCount: triggeredVideos.length,
      triggeredVideos
    });

  } catch (error: any) {
    console.error('❌ [Video Auto-Gen Dispatcher] Error:', error);
    return NextResponse.json({ error: error.message || 'Video auto-gen failed' }, { status: 500 });
  }
}
