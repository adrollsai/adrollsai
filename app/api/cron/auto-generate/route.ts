import { NextResponse } from 'next/server';
import { createClient } from '@supabase/supabase-js';

// Force dynamic execution to bypass Vercel static build cache
export const dynamic = 'force-dynamic';
export const fetchCache = 'force-no-store';
export const revalidate = 0;

const supabaseAdmin = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY!
);

export async function GET(request: Request) {
  return handleAutoGenerateDispatcher(request);
}

export async function POST(request: Request) {
  return handleAutoGenerateDispatcher(request);
}

async function handleAutoGenerateDispatcher(request: Request) {
  try {
    // 1. Security check to ensure only authorized triggers hit this dispatcher
    const authHeader = request.headers.get('authorization');
    const url = new URL(request.url);
    const token = authHeader ? authHeader.replace(/^Bearer\s+/i, '').trim() : '';
    const cronSecret = url.searchParams.get('cronSecret')?.trim() || token || null;
    const expectedSecret = process.env.CRON_SECRET ? process.env.CRON_SECRET.trim() : '';

    if (expectedSecret && cronSecret !== expectedSecret) {
      console.warn('[Auto-Generate Dispatcher] Unauthorized access attempt.');
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }

    const isForce = url.searchParams.get('force') === 'true';

    // 2. Tenant automation policy: master switch + per-feature toggle.
    const { atLocalTime, localHour } = await import('@/lib/automation/calling-cadence')

    const { data: policies } = await supabaseAdmin
      .from('tenant_automations')
      .select('user_id, master_enabled, daily_creative, timezone, creative_hour_local, bill_automation')
    const policyByTenant = new Map<string, any>()
    for (const p of policies || []) policyByTenant.set(p.user_id, p)

    // 3. Every enrolled property.
    const { data: properties, error: propError } = await supabaseAdmin
      .from('properties')
      .select('id, title, user_id, configurations')
      .eq('auto_generate', true);

    if (propError) throw propError;

    if (!properties || properties.length === 0) {
      return NextResponse.json({ message: 'No properties scheduled for auto-generation' });
    }

    // Group by tenant — the rotation is per tenant, not global.
    const byTenant = new Map<string, typeof properties>()
    for (const prop of properties) {
      const arr = byTenant.get(prop.user_id) || []
      arr.push(prop)
      byTenant.set(prop.user_id, arr)
    }

    const orderIndex = (prop: any): number => {
      try {
        const cfg = typeof prop.configurations === 'string'
          ? JSON.parse(prop.configurations || '{}')
          : (prop.configurations || {})
        const n = Number(cfg?.round_robin_order)
        return Number.isFinite(n) ? n : 9999
      } catch {
        return 9999
      }
    }

    const nowUtc = new Date();
    const propertiesToQueue: any[] = [];
    const skipped: any[] = [];

    for (const [tenantId, tenantProps] of byTenant) {
      const policy = policyByTenant.get(tenantId)

      // Respect the tenant's switches. A tenant with no policy row yet is
      // treated as enabled (the migration backfills, but do not break on a race).
      if (policy && (!policy.master_enabled || !policy.daily_creative)) {
        skipped.push({ tenantId, reason: 'disabled_by_tenant' })
        continue
      }

      const tz: string = policy?.timezone || 'Asia/Kolkata'
      const tenantHour: number = Number(policy?.creative_hour_local ?? 9)
      const todayStart = atLocalTime(nowUtc, 0, 0, tz).toISOString()

      // ONE creative per tenant per day — that is what "round-robin" means.
      if (!isForce) {
        const { count: doneToday } = await supabaseAdmin
          .from('assets')
          .select('id', { head: true, count: 'exact' })
          .eq('user_id', tenantId)
          .eq('type', 'image')
          .gte('created_at', todayStart)

        if (doneToday && doneToday > 0) {
          skipped.push({ tenantId, reason: 'already_generated_today' })
          continue
        }
      }

      // Strict rotation over the user's saved order (the reorder tile writes
      // configurations.round_robin_order). Whoever went last, the next in the
      // list is up.
      const ordered = [...tenantProps].sort(
        (a, b) => orderIndex(a) - orderIndex(b) || String(a.id).localeCompare(String(b.id))
      )

      const { data: recentAssets } = await supabaseAdmin
        .from('assets')
        .select('property_id, created_at')
        .eq('user_id', tenantId)
        .not('property_id', 'is', null)
        .order('created_at', { ascending: false })
        .limit(200)

      const lastByProp = new Map<string, number>()
      for (const a of recentAssets || []) {
        if (a.property_id && !lastByProp.has(a.property_id)) {
          lastByProp.set(a.property_id, new Date(a.created_at).getTime())
        }
      }

      let lastIdx = -1
      let lastMs = -1
      ordered.forEach((p, i) => {
        const ms = lastByProp.get(p.id)
        if (ms !== undefined && ms > lastMs) {
          lastMs = ms
          lastIdx = i
        }
      })

      const next = lastIdx >= 0
        ? ordered[(lastIdx + 1) % ordered.length]
        : ordered[0]

      // Per-property time_of_day still wins over the tenant default.
      let timeOfDay = ''
      try {
        const cfg = typeof next.configurations === 'string'
          ? JSON.parse(next.configurations || '{}')
          : (next.configurations || {})
        timeOfDay = cfg?.auto_gen_settings?.time_of_day || ''
      } catch {}
      const targetHour = timeOfDay
        ? (parseInt(timeOfDay.split(':')[0], 10) || tenantHour)
        : tenantHour

      // Credit gate: never generate (and never pay the image provider) on an
      // empty balance. Balance-only — see lib/automation/billing.ts for why
      // hasEnoughCredits() is unsuitable here. Deduction happens in the worker,
      // after the asset exists, so a failed generation is not billed.
      if (policy?.bill_automation !== false) {
        try {
          const { canAffordAutomation } = await import('@/lib/automation/billing')
          const { CREDIT_COSTS } = await import('@/utils/credits')
          const afford = await canAffordAutomation(supabaseAdmin, tenantId, CREDIT_COSTS.AI_IMAGE_GENERATION)
          if (!afford.ok) {
            skipped.push({ tenantId, reason: 'insufficient_credits', balance: afford.balance })
            continue
          }
        } catch (creditErr: any) {
          console.warn('[Auto-Generate Dispatcher] credit check failed:', creditErr?.message)
        }
      }

      const currentLocalHour = localHour(nowUtc, tz)
      if (!isForce && currentLocalHour < targetHour) {
        skipped.push({ tenantId, reason: `before_${targetHour}:00_${tz}` })
        continue
      }

      propertiesToQueue.push(next)
    }

    const currentIstHour = localHour(nowUtc, 'Asia/Kolkata')

    if (propertiesToQueue.length === 0) {
      return NextResponse.json({
        message: 'No properties due for auto-generation at this hour',
        currentIstHour,
        totalEnabled: properties.length,
        skipped
      });
    }

    console.log(`[Auto-Generate Dispatcher] Processing auto-generation for ${propertiesToQueue.length} properties (out of ${properties.length} enabled)...`);

    // Construct the destination worker URL dynamically using public domain
    const forwardedHost = request.headers.get('x-forwarded-host');
    const forwardedProto = request.headers.get('x-forwarded-proto') || 'https';
    let baseUrl = `${url.origin}`;
    if (forwardedHost && !forwardedHost.includes('localhost') && !forwardedHost.includes('local.')) {
      baseUrl = `${forwardedProto}://${forwardedHost}`;
    } else if (process.env.NEXT_PUBLIC_APP_URL && !process.env.NEXT_PUBLIC_APP_URL.includes('localhost') && !process.env.NEXT_PUBLIC_APP_URL.includes('local.')) {
      baseUrl = process.env.NEXT_PUBLIC_APP_URL;
    } else {
      baseUrl = 'https://app.nobogent.com';
    }

    const workerUrl = `${baseUrl.replace(/\/$/, '')}/api/cron/auto-generate/worker`;
    const qstashToken = process.env.QSTASH_TOKEN;

    let qstashCount = 0;
    let directCount = 0;

    const publishPromises = propertiesToQueue.map(async (prop) => {
      let publishedViaQStash = false;

      if (qstashToken) {
        try {
          const qstashPublishUrl = `https://qstash.upstash.io/v2/publish/${workerUrl}`;
          const res = await fetch(qstashPublishUrl, {
            method: 'POST',
            headers: {
              'Authorization': `Bearer ${qstashToken}`,
              'Content-Type': 'application/json',
              'Upstash-Forward-Authorization': `Bearer ${process.env.CRON_SECRET || ''}`
            },
            body: JSON.stringify({ id: prop.id })
          });

          if (res.ok) {
            publishedViaQStash = true;
            qstashCount++;
          } else {
            const errText = await res.text();
            console.warn(`[Auto-Generate Dispatcher] QStash publish failed (${res.status}: ${errText}) for property ${prop.id}. Triggering direct worker execution.`);
          }
        } catch (qErr: any) {
          console.warn(`[Auto-Generate Dispatcher] QStash network error: ${qErr.message}. Triggering direct worker execution.`);
        }
      }

      // Resilient fallback: directly trigger worker so rate-limited QStash never halts auto-generation
      if (!publishedViaQStash) {
        try {
          console.log(`[Auto-Generate Dispatcher] Invoking direct worker for property "${prop.title}" (${prop.id})...`);
          const workerRes = await fetch(workerUrl, {
            method: 'POST',
            headers: {
              'Authorization': `Bearer ${process.env.CRON_SECRET || ''}`,
              'Content-Type': 'application/json'
            },
            body: JSON.stringify({ id: prop.id })
          });

          if (workerRes.ok) {
            directCount++;
            console.log(`[Auto-Generate Dispatcher] Direct worker succeeded for property ${prop.id}`);
          } else {
            const wErr = await workerRes.text();
            console.error(`[Auto-Generate Dispatcher] Direct worker failed (${workerRes.status}) for property ${prop.id}:`, wErr);
          }
        } catch (directErr: any) {
          console.error(`[Auto-Generate Dispatcher] Direct worker invocation error for property ${prop.id}:`, directErr);
        }
      }
    });

    await Promise.allSettled(publishPromises);
    console.log(`[Auto-Generate Dispatcher] Finished dispatching. QStash: ${qstashCount}, Direct: ${directCount}`);

    return NextResponse.json({ 
      success: true, 
      processedCount: propertiesToQueue.length, 
      qstashQueued: qstashCount, 
      directExecuted: directCount 
    });
  } catch (err: any) {
    console.error('[Auto-Generate Dispatcher] Error:', err);
    return NextResponse.json({ error: 'Internal server error', details: err.message }, { status: 500 });
  }
}